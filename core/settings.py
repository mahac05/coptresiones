# ─── Описания CRF ───────────────────────────────────────────────────
def get_crf_description(crf: int) -> str:
    """Возвращает описание для данного значения CRF."""
    if crf <= 20:
        return "(высокое качество)"
    elif crf <= 25:
        return "(стандартное)"
    elif crf <= 30:
        return "(хорошее сжатие)"
    else:
        return "(сильное сжатие)"


